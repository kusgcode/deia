export const categories = [...new Set(products.map(p => p.category))];

export function getProductBySlug(slug) {
  return products.find(p => p.slug === slug) || null;
}

export function getProductsByCategory(category) {
  if (!category || category === 'All') return products;
  return products.filter(p => p.category === category);
}

export function searchProducts(query) {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.shortDescription.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.tags.some(t => t.toLowerCase().includes(q))
  );
}

export function getRelatedProducts(currentSlug, limit = 4) {
  const current = getProductBySlug(currentSlug);
  if (!current) return products.slice(0, limit);
  const related = products.filter(p => p.slug !== currentSlug);
  const sameCategory = related.filter(p => p.category === current.category);
  const others = related.filter(p => p.category !== current.category);
  return [...sameCategory, ...others].slice(0, limit);
}
